// Flags applied to every yt-dlp invocation.
// - android client: bypasses bot detection for most videos
// - js-runtimes node: use installed Node.js for JS-based extraction
// - cookies: optional file path via YTDLP_COOKIES_FILE env var (Netscape format)
function ytdlpBase(): string[] {
  const base = [
    "--no-check-certificate",
    "--extractor-args", "youtube:player_client=android,web",
    "--js-runtimes", "node",
    "--no-playlist",
  ];
  const cookiesFile = process.env.YTDLP_COOKIES_FILE;
  if (cookiesFile) base.push("--cookies", cookiesFile);
  return base;
}

// Piped instances used as fallback when YouTube blocks direct yt-dlp on datacenter IPs.
const PIPED_INSTANCES = [
  "https://pipedapi.kavin.rocks",
  "https://api.piped.projectsegfault.net",
  "https://piped-api.garudalinux.org",
];

interface PipedData {
  title: string;
  duration: number;
  thumbnailUrl: string;
  uploader: string;
  videoStreams: Array<{ url: string; mimeType: string; quality: string; videoOnly: boolean; bitrate: number }>;
  audioStreams: Array<{ url: string; mimeType: string; bitrate: number }>;
  subtitles: Array<{ url: string; mimeType: string; code: string; autoGenerated: boolean }>;
}

function extractYouTubeId(url: string): string | null {
  const m = url.match(/(?:v=|\/v\/|youtu\.be\/|\/embed\/|\/shorts\/)([a-zA-Z0-9_-]{11})/);
  return m?.[1] ?? null;
}

function isBotError(msg: string): boolean {
  return msg.includes("Sign in") || msg.includes("bot") || msg.includes("cookies") || msg.includes("Login");
}

async function fetchPiped(videoId: string): Promise<PipedData | null> {
  for (const instance of PIPED_INSTANCES) {
    try {
      const resp = await fetch(`${instance}/streams/${videoId}`, {
        headers: { "User-Agent": "PeakClipper/1.0" },
        signal: AbortSignal.timeout(10_000),
      });
      if (!resp.ok) continue;
      return await resp.json() as PipedData;
    } catch { /* try next */ }
  }
  return null;
}

// YouTube oEmbed — always works for public videos, no auth needed
async function fetchOembed(videoId: string): Promise<{ title: string; channel: string; thumbnail: string } | null> {
  try {
    const url = `https://www.youtube.com/oembed?url=https://www.youtube.com/watch?v=${videoId}&format=json`;
    const resp = await fetch(url, { signal: AbortSignal.timeout(8_000) });
    if (!resp.ok) return null;
    const d = await resp.json() as { title: string; author_name: string; thumbnail_url: string };
    return { title: d.title, channel: d.author_name, thumbnail: d.thumbnail_url };
  } catch { return null; }
}

// cobalt.tools — free YouTube downloader API, handles auth on their side
async function fetchCobaltUrl(url: string): Promise<string | null> {
  try {
    const resp = await fetch("https://api.cobalt.tools/", {
      method: "POST",
      headers: { "Content-Type": "application/json", "Accept": "application/json" },
      body: JSON.stringify({ url, videoQuality: "720", filenameStyle: "basic" }),
      signal: AbortSignal.timeout(20_000),
    });
    if (!resp.ok) return null;
    const d = await resp.json() as { status: string; url?: string };
    return d.url ?? null;
  } catch { return null; }
}

const sleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms));

